// asyncpgErrorName is the asyncpg exception class Python puts in
// "the database could not be read (<name>)". The classes are asyncpg 0.30.0.
// A SQLSTATE that asyncpg does not define is UnknownPostgresError, which is
// the class asyncpg uses for an unknown code.
func asyncpgErrorName(code string) string {
	if name, ok := asyncpgErrors[code]; ok {
		return name
	}
	return "UnknownPostgresError"
}

