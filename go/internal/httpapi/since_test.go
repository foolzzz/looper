package httpapi

import (
	"testing"
	"time"
)

func TestParseSinceDay(t *testing.T) {
	accept := []struct {
		in      string
		y, m, d int
	}{
		{in: "2010-01-01", y: 2010, m: 1, d: 1},
		{in: "20100101", y: 2010, m: 1, d: 1},
		{in: "0999-01-01", y: 999, m: 1, d: 1},
		{in: "0001-01-01", y: 1, m: 1, d: 1},
		{in: "9999-12-31", y: 9999, m: 12, d: 31},
		{in: "2000-02-29", y: 2000, m: 2, d: 29},
		{in: "2012-02-29", y: 2012, m: 2, d: 29},
		{in: "2010-W01-1", y: 2010, m: 1, d: 4},
		{in: "2010-W01", y: 2010, m: 1, d: 4},
		{in: "2010W011", y: 2010, m: 1, d: 4},
		{in: "2010W01", y: 2010, m: 1, d: 4},
		{in: "2020-W53-1", y: 2020, m: 12, d: 28},
		{in: "2020-W53", y: 2020, m: 12, d: 28},
		{in: "2015-W53-1", y: 2015, m: 12, d: 28},
		{in: "2015-W53-7", y: 2016, m: 1, d: 3},
		{in: "2015W537", y: 2016, m: 1, d: 3},
		{in: "2009-W01-1", y: 2008, m: 12, d: 29},
		{in: "2009W011", y: 2008, m: 12, d: 29},
		{in: "2009-W53-1", y: 2009, m: 12, d: 28},
		{in: "2004-W53-1", y: 2004, m: 12, d: 27},
		{in: "0001-W01-1", y: 1, m: 1, d: 1},
		{in: "0001W011", y: 1, m: 1, d: 1},
		{in: "9999-W52-1", y: 9999, m: 12, d: 27},
	}
	for _, tt := range accept {
		t.Run(tt.in, func(t *testing.T) {
			got, ok := parseSinceDay(tt.in)
			if !ok {
				t.Fatal("rejected")
			}
			y, m, d := got.Date()
			if y != tt.y || int(m) != tt.m || d != tt.d || got.Location() != time.UTC {
				t.Fatalf("got %s, want %04d-%02d-%02d UTC", got, tt.y, tt.m, tt.d)
			}
		})
	}

	reject := []string{
		"", "nope", "2010", "2010-01", "2010-1-1", "2010-01-1", "2010-1-01",
		"2010-W1-1", "2010-w01-1", "2010-W011", "2010W01-1", "2010-W01-0", "2010-W01-8",
		"2010-W01-01", "2010W1", "2010-W00-1", "2010-W54-1", "2010-W53-1", "2010-W53",
		"2010W53", "2010W531", "2010-W53-7", "9999-W52-7", "9999W527",
		"2010-01-01T00:00:00", "+2010-01-01", "+20100101", "2010-001", "2010001",
		" 2010-01-01", "2010-01-01 ", "2010-01-01\n", "\t2010-01-01",
		"1900-02-29", "2011-02-29", "2010-02-29", "20100229", "20100230", "2010-02-31",
		"2010-13-01", "0000-01-01", "2010/01/01", "01-01-2010",
	}
	for _, in := range reject {
		t.Run("reject "+in, func(t *testing.T) {
			if _, ok := parseSinceDay(in); ok {
				t.Fatalf("accepted %q", in)
			}
		})
	}
}
