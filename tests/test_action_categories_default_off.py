"""Main's write-call bytes with receipts absent or explicitly off; no model or channel is involved."""

import hashlib
import json

import pytest

from looper.agents.ops import Turn
from looper.agents.ops.service import ManagerOps, Platform
from tests.db_support import run_db


@pytest.mark.parametrize("setting", [None, "false"])
def test_write_results_blocks_and_audit_rows_match_main(monkeypatch, setting):
    async def body(pool):
        if setting is not None:
            await pool.execute("INSERT INTO system_settings (key, value) VALUES "
                               "('manager.action_receipts.enabled', $1)", setting)
        await pool.execute("INSERT INTO projects (id, name, background) VALUES ('proj-sample', 'sample', 'Before')")
        ops = ManagerOps(Platform(bus=None, task_router=None), url="http://127.0.0.1:9", token="synthetic")
        turn = Turn(channel="web", chat="sample-chat", message_id="sample-message")
        ops.begin_turn(turn, "sample-binding")
        try:
            changed = await ops.call("looper_projects", {"action": "update", "project": "sample", "background": "After"},
                                     binding="sample-binding")
            failed = await ops.call("looper_projects", {"action": "update", "project": "missing", "background": "After"},
                                    binding="sample-binding")
        finally:
            ops.end_turn(turn)
        # Captured from main 4b602aeed: only ids and timestamps generated by PostgreSQL are excluded.
        rows = [dict(row) for row in await pool.fetch(
            "SELECT channel, chat, message_id, tool, arguments, risk, status, error_code, result, "
            "confirmation_id, task_id, manager_id, client_id FROM manager_actions ORDER BY id")]
        for row in rows:
            for field in ("arguments", "result"):
                row[field] = json.loads(row[field]) if row[field] is not None else None
        observed = json.dumps(_normalized({"answers": [changed, failed], "blocks": turn.blocks, "rows": rows}),
                              sort_keys=True, ensure_ascii=False)
        assert hashlib.sha256(observed.encode()).hexdigest() == MAIN_SHA256
        assert await pool.fetchval("SELECT background FROM projects WHERE id = 'proj-sample'") == "After"

    run_db(body, monkeypatch, timeout=30)


def _normalized(value):
    if isinstance(value, dict):
        return {key: "<timestamp>" if key in ("created_at", "updated_at") else _normalized(item)
                for key, item in value.items()}
    if isinstance(value, list):
        return [_normalized(item) for item in value]
    return value


# Main 4b602aeed: full results, blocks and audit payloads; only generated timestamps/row ids are normalized.
MAIN_SHA256 = "62f8977be948c2dcb1c42699d0b3b4299d94d4e167eb5f59340418fce6f4761e"
